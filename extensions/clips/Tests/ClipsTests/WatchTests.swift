import XCTest
@testable import ClipsCore

/// A clipboard that counts what was asked of it.
final class FakeBoard: ClipsCore.Pasteboard {
    var changeCount = 0
    var types: [String] = []
    var values: [String: Data] = [:]
    var filePaths: [String] = []
    var counterReads = 0
    var typeReads = 0
    var contentReads = 0
    var written: (text: String?, data: Data?, files: [String])?

    func copy(_ types: [String: Data], files: [String] = []) {
        changeCount += 1
        self.types = Array(types.keys) + (files.isEmpty ? [] : [ClipType.fileURL])
        values = types
        filePaths = files
    }

    func copyText(_ text: String, also: [String] = []) {
        var all = [ClipType.text: Data(text.utf8)]
        for marker in also { all[marker] = Data() }
        copy(all)
    }

    func data(forType type: String) -> Data? {
        contentReads += 1
        return values[type]
    }

    func string(forType type: String) -> String? {
        contentReads += 1
        return values[type].map { String(decoding: $0, as: UTF8.self) }
    }

    func files() -> [String] {
        contentReads += 1
        return filePaths
    }

    func put(text: String?, data: Data?, dataType: String?, files: [String]) -> Int {
        written = (text, data, files)
        changeCount += 1
        return changeCount
    }
}

/// Counts reads of the counter and the kinds, by wrapping the fake.
final class CountingBoard: ClipsCore.Pasteboard {
    let inner = FakeBoard()
    var changeCount: Int {
        inner.counterReads += 1
        return inner.changeCount
    }
    var types: [String] {
        inner.typeReads += 1
        return inner.types
    }
    func data(forType type: String) -> Data? { inner.data(forType: type) }
    func string(forType type: String) -> String? { inner.string(forType: type) }
    func files() -> [String] { inner.files() }
    func put(text: String?, data: Data?, dataType: String?, files: [String]) -> Int {
        inner.put(text: text, data: data, dataType: dataType, files: files)
    }
}

final class WatchTests: XCTestCase {
    func testConcealedCopiesAreNeverKept() {
        let board = FakeBoard()
        let watcher = Watcher(pasteboard: board, frontmost: { "com.apple.Safari" })
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            board.copyText("hunter2", also: [marker])
            XCTAssertNil(watcher.tick(), marker)
        }
        // An ordinary copy is kept.
        board.copyText("hello")
        XCTAssertEqual(watcher.tick()?.text, "hello")
    }

    func testIgnoredAppsAreNeverKept() {
        let board = FakeBoard()
        var front = "com.1password.1password"
        let watcher = Watcher(pasteboard: board, frontmost: { front })
        board.copyText("s3cret")
        XCTAssertNil(watcher.tick())
        for app in ["com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords"] {
            front = app
            board.copyText("s3cret")
            XCTAssertNil(watcher.tick(), app)
        }
        // An app you add is ignored too.
        front = "com.example.vault"
        watcher.ignoredApps.insert(front)
        board.copyText("s3cret")
        XCTAssertNil(watcher.tick())
        front = "com.apple.TextEdit"
        board.copyText("fine")
        XCTAssertEqual(watcher.tick()?.source, "com.apple.TextEdit")
    }

    func testContentsReadOnlyAfterTypesPass() {
        let board = FakeBoard()
        let watcher = Watcher(pasteboard: board, frontmost: { nil })
        board.copyText("hunter2", also: ["org.nspasteboard.ConcealedType"])
        _ = watcher.tick()
        XCTAssertEqual(board.contentReads, 0, "a secret's contents are never read, not even into memory")
        board.copyText("hello")
        _ = watcher.tick()
        XCTAssertGreaterThan(board.contentReads, 0)
    }

    func testIdleIsOneCounterRead() {
        let board = CountingBoard()
        let watcher = Watcher(pasteboard: board, frontmost: { nil })
        let start = board.inner.counterReads
        for _ in 0..<100 { _ = watcher.tick() }
        XCTAssertEqual(board.inner.counterReads - start, 100, "one counter read a tick")
        XCTAssertEqual(board.inner.typeReads, 0, "nothing else while nothing was copied")
        XCTAssertEqual(board.inner.contentReads, 0)
    }

    func testEachKindIsRead() {
        let board = FakeBoard()
        let watcher = Watcher(pasteboard: board, frontmost: { nil })
        board.copy([:], files: ["/Users/kj/Desktop/a.pdf", "/Users/kj/b.png"])
        XCTAssertEqual(watcher.tick(), Capture(kind: .files, text: "/Users/kj/Desktop/a.pdf\n/Users/kj/b.png",
                                               files: ["/Users/kj/Desktop/a.pdf", "/Users/kj/b.png"]))
        board.copy([ClipType.png: Data([1, 2, 3])])
        XCTAssertEqual(watcher.tick()?.kind, .image)
        board.copy([ClipType.rtf: Data("{\\rtf1 hi}".utf8), ClipType.text: Data("hi".utf8)])
        let rich = watcher.tick()
        XCTAssertEqual(rich?.kind, .rich)
        XCTAssertEqual(rich?.text, "hi")
        XCTAssertEqual(rich?.dataType, ClipType.rtf)
        board.copy(["com.example.unknown": Data([9])])
        XCTAssertNil(watcher.tick(), "nothing Clips can keep")
    }

    func testOwnPastesPausesAndIgnoreNext() {
        let board = FakeBoard()
        let watcher = Watcher(pasteboard: board, frontmost: { nil })
        // Clips' own copy (to paste) isn't a new copy.
        watcher.own(board.put(text: "again", data: nil, dataType: nil, files: []))
        XCTAssertNil(watcher.tick())
        watcher.ignoreNext = true
        board.copyText("skip me")
        XCTAssertNil(watcher.tick())
        board.copyText("keep me")
        XCTAssertEqual(watcher.tick()?.text, "keep me", "ignore-next is once")
        let now = Date()
        watcher.pausedUntil = now.addingTimeInterval(900)
        board.copyText("paused")
        XCTAssertNil(watcher.tick(now: now))
        board.copyText("back")
        XCTAssertEqual(watcher.tick(now: now.addingTimeInterval(901))?.text, "back")
    }
}
